#!/usr/bin/env python3
"""Regenerate the "## Recent Posts" section of static/llms.txt from content/posts/.

Usage: gen-llms.py

Only the block between the "## Recent Posts" heading and the next "## " heading
is rewritten; every other section of llms.txt stays hand-edited. Run from the
Makefile before `zola build` so the published llms.txt always lists the latest
posts. Slugs are derived the same way Zola does: a leading YYYY-MM-DD- date
prefix on the filename is stripped (an explicit `slug`/`path` in frontmatter
wins if present).
"""
from __future__ import annotations

import re
import sys
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
POSTS_DIR = REPO / "content" / "posts"
LLMS = REPO / "static" / "llms.txt"

RECENT_COUNT = 8
HEADING = "## Recent Posts"
NOTE = (
    "Full archive at `/posts/`. "
    "Machine-readable list of every post (with content) at `/atom.xml`."
)

FRONTMATTER_FENCE = "+++"
DATE_PREFIX_RE = re.compile(r"^(\d{4})-(\d{2})-(\d{2})-(.+)$")


def parse_frontmatter(text: str) -> dict[str, str]:
    lines = text.splitlines()
    if not lines or lines[0].strip() != FRONTMATTER_FENCE:
        return {}
    end = next(
        (i for i, ln in enumerate(lines[1:], start=1) if ln.strip() == FRONTMATTER_FENCE),
        None,
    )
    if end is None:
        return {}
    meta: dict[str, str] = {}
    for raw in lines[1:end]:
        if "=" in raw and not raw.lstrip().startswith("#"):
            key, _, value = raw.partition("=")
            meta[key.strip()] = value.strip().strip('"')
    return meta


def slug_for(path: Path, meta: dict[str, str]) -> str:
    if meta.get("path"):
        return meta["path"].strip("/").removeprefix("posts/").strip("/")
    if meta.get("slug"):
        return meta["slug"]
    stem = path.stem
    m = DATE_PREFIX_RE.match(stem)
    return m.group(4) if m else stem


def collect_posts() -> list[dict[str, object]]:
    posts: list[dict[str, object]] = []
    for path in POSTS_DIR.glob("*.md"):
        if path.name == "_index.md":
            continue
        meta = parse_frontmatter(path.read_text(encoding="utf-8"))
        if meta.get("draft", "").lower() == "true":
            continue
        try:
            post_date = date.fromisoformat(meta["date"])
        except (KeyError, ValueError):
            continue  # no usable date -> can't be "recent"
        posts.append(
            {
                "date": post_date,
                "title": meta.get("title", path.stem),
                "description": meta.get("description", "").strip(),
                "slug": slug_for(path, meta),
            }
        )
    posts.sort(key=lambda p: p["date"], reverse=True)
    return posts


def render_section(posts: list[dict[str, object]]) -> list[str]:
    out = [
        HEADING,
        "",
        "<!-- auto-generated by bin/gen-llms.py on each build — edit posts, not this block -->",
        "",
    ]
    for p in posts[:RECENT_COUNT]:
        line = f"- [{p['title']}](/posts/{p['slug']}/) - {p['date'].isoformat()}"
        if p["description"]:
            line += f" - {p['description']}"
        out.append(line)
    out += ["", NOTE]
    return out


def splice(existing: str, section: list[str]) -> str:
    lines = existing.splitlines()
    try:
        start = next(i for i, ln in enumerate(lines) if ln.strip() == HEADING)
    except StopIteration:
        sys.exit(f"error: '{HEADING}' heading not found in {LLMS}")
    end = next(
        (i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")),
        len(lines),
    )
    # Preserve a single trailing blank line before the following heading.
    tail = lines[end:]
    new_lines = lines[:start] + section + ([""] + tail if tail else [])
    return "\n".join(new_lines) + "\n"


def main() -> None:
    posts = collect_posts()
    if not posts:
        sys.exit(f"error: no dated posts found in {POSTS_DIR}")
    updated = splice(LLMS.read_text(encoding="utf-8"), render_section(posts))
    LLMS.write_text(updated, encoding="utf-8")
    shown = min(RECENT_COUNT, len(posts))
    print(f"gen-llms: wrote {shown} recent posts to {LLMS.relative_to(REPO)}", file=sys.stderr)


if __name__ == "__main__":
    main()
